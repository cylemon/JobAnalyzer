/**
 * 通用文本归一化 —— 全项目唯一的实现（04-construction.md 原则 ⑤）。
 *
 * 技能键、公司名 / 职位名的重复检测都从这里出发，禁止各自实现一套：
 * 「匹配引擎认为已掌握、排行榜认为缺失」这类静默错误，根源都是同一份数据被两套规则解释。
 */

/**
 * 归一化为可比较的键。
 *
 * 规则（03-architecture.md §4.1）：
 *  1. NFKC 规范化（全角 → 半角，如 Ｃ＋＋ → C++）
 *  2. 转小写
 *  3. 保留任意语言的字母 / 数字与 + # .（保护 c++ / c# / node.js），
 *     其余字符（空格、斜杠、括号、连字符等）一律视为分隔符
 *  4. 合并连续空白并去除首尾空白
 *
 * 返回空字符串表示输入不含任何有效字符，调用方必须显式报错（原则 ①），不得静默接受。
 */
export function normalizeKey(raw: string): string {
  return raw
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}+#.]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}
